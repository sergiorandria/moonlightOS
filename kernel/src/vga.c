// Bochs VBE dispi spec
#define VBE_DISPI_INDEX_ID          0x0
#define VBE_DISPI_INDEX_XRES        0x1
#define VBE_DISPI_INDEX_YRES        0x2
#define VBE_DISPI_INDEX_BPP         0x3
#define VBE_DISPI_INDEX_ENABLE      0x4
#define VBE_DISPI_ID5               0xB0C5
#define VBE_DISPI_ENABLED           0x01
#define VBE_DISPI_LFB_ENABLED       0x40
#define VBE_DISPI_NOCLEARMEM        0x80
#define VGA_BAR2_BASE 0x41000000
#define VGA_BAR2_SIZE PAGE_SIZE

kerror_t vga_init(vspace_t *vs) {
    size_t fb_size = VGA_WIDTH * VGA_HEIGHT * (VGA_BPP/8);
    fb_size = (fb_size + PAGE_SIZE-1) & ~(PAGE_SIZE-1);
    kerror_t e = vspace_map(vs, VGA_FB_BASE, VGA_FB_BASE, fb_size, 0x7, 0);
    if (e != ERR_OK) return e;
    e = vspace_map(vs, VGA_BAR2_BASE, VGA_BAR2_BASE, VGA_BAR2_SIZE, 0x7, 0);
    if (e != ERR_OK) return e;
    e = vspace_map(vs, 0x30000000, 0x30000000, 0x1000000, 0x7, 0);
    if (e != ERR_OK) return e;
    fb = (volatile uint32_t*)VGA_FB_BASE;
    uart_puts("[VGA] PCI scan ECAM 0x30000000\n");
    int found = 0;
    uint32_t found_bar0 = 0, found_bar2 = 0;
    uintptr_t found_ecam = 0;
    for(int dev=0; dev<32; dev++){
        volatile uint32_t *ecam = (volatile uint32_t*)(0x30000000 | (dev<<15));
        uint32_t id = ecam[0];
        if(id==0xffffffff) continue;
        uint16_t ven = id & 0xFFFF;
        uint16_t did = (id>>16) & 0xFFFF;
        uart_puts("[VGA] PCI dev "); uart_hex32(dev);
        uart_puts(" vendor/device "); uart_hex32(id);
        uart_putc('\n');
        if(ven==0x1234 && did==0x1111){
            found = 1;
            found_ecam = (uintptr_t)ecam;
            uart_puts("[VGA] bochs-display found at dev "); uart_hex32(dev); uart_putc('\n');
            volatile uint32_t *bar0 = (volatile uint32_t*)((uintptr_t)ecam + 0x10);
            volatile uint32_t *bar1 = (volatile uint32_t*)((uintptr_t)ecam + 0x14);
            volatile uint32_t *bar2 = (volatile uint32_t*)((uintptr_t)ecam + 0x18);
            volatile uint32_t *bar3 = (volatile uint32_t*)((uintptr_t)ecam + 0x1C);
            volatile uint32_t *cmd  = (volatile uint32_t*)((uintptr_t)ecam + 0x04);
            uint32_t orig_bar0 = *bar0;
            uint32_t orig_bar2 = *bar2;
            uart_puts("[VGA] orig BAR0 "); uart_hex32(orig_bar0); uart_puts(" BAR2 "); uart_hex32(orig_bar2); uart_putc('\n');
            int bar0_64 = (orig_bar0 & 0x6) == 0x4;
            int bar2_64 = (orig_bar2 & 0x6) == 0x4;
            uart_puts("[VGA] BAR0 64-bit? "); uart_hex32(bar0_64); uart_puts(" BAR2 64-bit? "); uart_hex32(bar2_64); uart_putc('\n');
            *bar0 = VGA_FB_BASE;
            if(bar0_64) *bar1 = 0;
            *bar2 = VGA_BAR2_BASE;
            if(bar2_64) *bar3 = 0;
            __asm__ volatile("fence" ::: "memory");
            uint32_t read_bar0 = *bar0;
            uint32_t read_bar2 = *bar2;
            uart_puts("[VGA] programmed BAR0 "); uart_hex32(read_bar0); uart_puts(" BAR2 "); uart_hex32(read_bar2); uart_putc('\n');
            found_bar0 = read_bar0;
            found_bar2 = read_bar2;
            uint32_t c = *cmd;
            c |= 0x07;
            *cmd = c;
            __asm__ volatile("fence; sfence.vma" ::: "memory");
            uart_puts("[VGA] PCI CMD "); uart_hex32(c); uart_putc('\n');
            volatile uint16_t *vbe = (volatile uint16_t*)(VGA_BAR2_BASE + 0x500);
            uart_puts("[VGA] VBE via BAR2 MMIO "); uart_hex(VGA_BAR2_BASE + 0x500); 
            vbe[VBE_DISPI_INDEX_ID] = VBE_DISPI_ID5;
            vbe[VBE_DISPI_INDEX_XRES] = VGA_WIDTH;
            vbe[VBE_DISPI_INDEX_YRES] = VGA_HEIGHT;
            vbe[VBE_DISPI_INDEX_BPP] = 32;
            vbe[VBE_DISPI_INDEX_ENABLE] = VBE_DISPI_ENABLED | VBE_DISPI_LFB_ENABLED;
            __asm__ volatile("fence" ::: "memory");
            uart_puts("[VGA] VBE set "); uart_hex32(VGA_WIDTH); uart_putc('x'); uart_hex32(VGA_HEIGHT); uart_puts("x32 enable 0x41\n");
            uint16_t id_read = vbe[VBE_DISPI_INDEX_ID];
            uart_puts("[VGA] VBE ID readback "); uart_hex32(id_read); uart_putc('\n');
            break;
        }
    }
    if(!found){
        uart_puts("[VGA] FAIL bochs-display not found (0x1234:0x1111)\n");
        return ERR_NO_MEM;
    }
    fb_init_done=1;
    uart_puts("[VGA] BAR0="); uart_hex(found_bar0); uart_puts("[VGA] BAR2="); uart_hex(found_bar2);
    uart_puts("[VGA] ECAM "); uart_hex(found_ecam); 
    uart_puts("[VGA] init done, clearing FB\n");
    for(size_t i=0;i<100;i++) fb[i]=0x00000000;
    uart_puts("[VGA] FB clear done\n");
    for(int r=0;r<CONSOLE_ROWS;r++)
        for(int c=0;c<CONSOLE_COLS;c++)
            console_text[r][c]=' ';
    console_cx=0; console_cy=0; console_cursor=0;
    return ERR_OK;
}

int vga_is_initialized(void){ return fb_init_done; }

static void console_cell_draw(int col, int row, int invert);
static void console_cursor_show(void);

/* Full console reset: blank shadow + pixels, cursor home (drawn visible so
 * the input position is always obvious). Backs `clear` via the moonsh hook. */
void vga_console_clear(void){
    int r, c;
    size_t i, n;
    if(!fb_init_done) return;
    console_cursor = 0;
    for(r=0;r<CONSOLE_ROWS;r++)
        for(c=0;c<CONSOLE_COLS;c++)
            console_text[r][c] = ' ';
    n = (size_t)VGA_WIDTH * (size_t)VGA_HEIGHT;
    for(i=0;i<n;i++) fb[i] = CON_BG;
    console_cx = 0;
    console_cy = 0;
    console_cursor_show();
}

static void console_cell_draw(int col, int row, int invert){
    char c;
    const uint8_t *g;
    uint32_t fg, bg;
    int r, cc;
    if(col<0 || col>=CONSOLE_COLS || row<0 || row>=CONSOLE_ROWS) return;
    c = console_text[row][col];
    if((unsigned char)c<0x20 || (unsigned char)c>0x7E) c='?';
    g = font8x8[(unsigned char)c];
    fg = invert ? CON_BG : CON_FG;
    bg = invert ? CON_FG : CON_BG;
    for(r=0;r<CON_GLYPH_H;r++){
        uint8_t bits = g[r];
        for(cc=0;cc<CON_CELL_W;cc++){
            int px = col*CON_CELL_W+cc;
            int py = row*CON_CELL_H+r*2;
            uint32_t colr = (bits & (1u << cc)) ? fg : bg;
            fb[py*VGA_WIDTH+px]=colr;
            fb[(py+1)*VGA_WIDTH+px]=colr;
        }
    }
}

static void console_cursor_erase(void){
    if(console_cursor){ console_cursor=0; console_cell_draw(console_cx,console_cy,0); }
}

static void console_cursor_show(void){
    if(!console_cursor){ console_cursor=1; console_cell_draw(console_cx,console_cy,1); }
}

/* Scroll up one text row: shadow loop, pixel shift, blanked bottom line. */
static void vga_console_scroll(void){
    int r, c;
    size_t i, n;
    volatile uint32_t *dst, *src;
    if(!fb_init_done) return;
    console_cursor = 0;
    for(r=0;r<CONSOLE_ROWS-1;r++)
        for(c=0;c<CONSOLE_COLS;c++)
            console_text[r][c] = console_text[r+1][c];
    for(c=0;c<CONSOLE_COLS;c++)
        console_text[CONSOLE_ROWS-1][c] = ' ';
    /* dst < src: forward copy is overlap-safe. */
    dst = fb;
    src = fb + (size_t)VGA_WIDTH * CON_CELL_H;
    n = (size_t)VGA_WIDTH * ((size_t)VGA_HEIGHT - CON_CELL_H);
    for(i=0;i<n;i++) dst[i] = src[i];
    n = (size_t)VGA_WIDTH * (size_t)VGA_HEIGHT;
    for(i=(size_t)VGA_WIDTH*((size_t)VGA_HEIGHT-CON_CELL_H);i<n;i++) fb[i] = CON_BG;
    console_cx = 0;
    console_cy = CONSOLE_ROWS-1;
}

static void console_newline(void){
    console_cx = 0;
    console_cy++;
    if(console_cy >= CONSOLE_ROWS) vga_console_scroll();
}

void vga_console_putc(char c){
    int t;
    if(!fb_init_done) return;
    console_cursor_erase();
    if(c=='\r'){ console_cx=0; }
    else if(c=='\n'){ console_newline(); }
    else if(c=='\b'){ /* erase within the line; never eat the line above */
        if(console_cx>0){
            console_cx--;
            console_text[console_cy][console_cx]=' ';
            console_cell_draw(console_cx,console_cy,0);
        }
    }
    else if(c=='\t'){ /* tab stops every 8 columns */
        t = (console_cx+8) & ~7;
        if(t>=CONSOLE_COLS){ console_newline(); }
        else {
            for(;console_cx<t;console_cx++){
                console_text[console_cy][console_cx]=' ';
                console_cell_draw(console_cx,console_cy,0);
            }
        }
    }
    else {
        if((unsigned char)c<0x20 || (unsigned char)c>0x7E) c='?';
        console_text[console_cy][console_cx]=c;
        console_cell_draw(console_cx,console_cy,0);
        console_cx++;
        if(console_cx>=CONSOLE_COLS) console_newline();
    }
    console_cursor_show();
}

void vga_console_puts(const char *s){
    if(!s) return;
    while(*s) vga_console_putc(*s++);
}

/* Strong impl of moonsh's weak clear hook (userspace ELF has none): clear
 * the visible console(s). The framebuffer has no ANSI parser, so VGA gets
 * a real blank; the serial terminal gets ANSI only in mirror mode (in
 * split mode the launch terminal keeps the boot log untouched). */
void moonsh_console_clear(void){
    vga_console_clear();
    if(!console_is_split())
        uart_puts("\x1b[2J\x1b[H");
}

void vga_clear(uint32_t color){
    if(!fb_init_done) return;
    for(size_t i=0;i<VGA_WIDTH*VGA_HEIGHT;i++) fb[i]=color;
}

static void draw_char(int x, int y, char c, uint32_t fg, uint32_t bg){
    if((unsigned char)c<0x20 || (unsigned char)c>0x7E) c='?';
    const uint8_t *g = font8x8[(unsigned char)c];
    for(int row=0;row<8;row++){
        uint8_t bits = g[row];
        for(int col=0;col<8;col++){
            int px = x*8+col;
            int py = y*16+row*2;
            if(px>=VGA_WIDTH || py>=VGA_HEIGHT) continue;
            uint32_t colr = (bits & (1 << col)) ? fg : bg;
            fb[py*VGA_WIDTH+px]=colr;
            if(py+1<VGA_HEIGHT) fb[(py+1)*VGA_WIDTH+px]=colr;
        }
    }
}

void vga_puts(const char *s){
    if(!fb_init_done) return;
    int x=0,y=0;
    while(*s){
        if(*s=='\n'){ x=0; y++; s++; continue; }
        draw_char(x,y,*s,0x00FFFFFF,0x00000000);
        x++; if(x>=VGA_WIDTH/8){ x=0; y++; }
        s++;
    }
}
void vga_puts_at(const char *s, int x, int y, uint32_t fg, uint32_t bg){
    if(!fb_init_done) return;
    int cx=x, cy=y;
    while(*s){
        if(*s=='\n'){ cx=x; cy++; s++; continue; }
        draw_char(cx,cy,*s,fg,bg);
        cx++; s++;
    }
}
void vga_render_text(const char *text, int x, int y, uint32_t fg, uint32_t bg){
    if(!fb_init_done || !text) return;
    int cx=x, cy=y;
    while(*text){
        if(*text=='\n'){ cx=x; cy++; text++; continue; }
        draw_char(cx,cy,*text,fg,bg);
        cx++;
        if(cx>=VGA_WIDTH/8){ cx=x; cy++; }
        text++;
    }
}
void vga_draw_hello(void){
    if(!fb_init_done) return;
    vga_console_clear();
    vga_console_puts("Hello world\n");
}
