/* ---------- console state --------------------------------------------- */
typedef struct {
    int col;
    int row;
    int initialized;
} fbcon_t;

static fbcon_t fbcon = {0, 0, 0};

/* ---------- low-level pixel/rect --------------------------------------- */
static inline void fb_pixel(int x, int y, uint32_t color)
{
    if (x >= 0 && x < FB_WIDTH && y >= 0 && y < FB_HEIGHT) {
        volatile uint32_t *fb = (volatile uint32_t *)FB_KVA;
        fb[(unsigned)y * (FB_STRIDE / 4) + (unsigned)x] = color;
    }
}

static inline void fb_rect(int x, int y, int w, int h, uint32_t color)
{
    for (int yy = y; yy < y + h && yy < FB_HEIGHT; yy++)
        for (int xx = x; xx < x + w && xx < FB_WIDTH; xx++)
            fb_pixel(xx, yy, color);
}

/* ---------- scrolling -------------------------------------------------- */
static inline void fb_scroll(void)
{
    volatile uint32_t *fb = (volatile uint32_t *)FB_KVA;
    int stride = FB_STRIDE / 4;
    for (int y = FB_FONT_H; y < FB_HEIGHT; y++)
        for (int x = 0; x < FB_WIDTH; x++)
            fb[(y - FB_FONT_H) * stride + x] = fb[y * stride + x];
    fb_rect(0, FB_HEIGHT - FB_FONT_H, FB_WIDTH, FB_FONT_H, FB_COLOR_BLACK);
}

/* ---------- character renderer ----------------------------------------- *
 * Uses the real 8×16 VGA bitmap font.  fg/bg are XRGB8888 values.        */
static inline void fb_draw_char(char c, int col, int row,
                                 uint32_t fg, uint32_t bg)
{
    if (col < 0 || col >= FB_CON_COLS || row < 0 || row >= FB_CON_ROWS)
        return;
    unsigned idx = (unsigned)(unsigned char)c;
    if (idx >= 128) idx = 0;
    const uint8_t *glyph = fb_font8x16[idx];
    int x0 = col * FB_FONT_W;
    int y0 = row * FB_FONT_H;
    for (int gy = 0; gy < FB_FONT_H; gy++) {
        uint8_t row_bits = glyph[gy];
        for (int gx = 0; gx < FB_FONT_W; gx++) {
            uint32_t color = (row_bits & (0x80u >> (unsigned)gx)) ? fg : bg;
            fb_pixel(x0 + gx, y0 + gy, color);
        }
    }
}

/* ---------- public API ------------------------------------------------- */

/* Initialise the console: black background, reset cursor. */
static inline void fbcon_clear(void)
{
    fb_rect(0, 0, FB_WIDTH, FB_HEIGHT, FB_COLOR_BLACK);
    fbcon.col = 0;
    fbcon.row = 0;
    fbcon.initialized = 1;
}

/* Put one character (handles \n, \r, tab). */
static inline void fbcon_putc(char c)
{
    if (!fbcon.initialized) return;
    if (c == '\n') {
        fbcon.col = 0;
        fbcon.row++;
    } else if (c == '\r') {
        fbcon.col = 0;
    } else if (c == '\t') {
        fbcon.col = (fbcon.col + 8) & ~7;
        if (fbcon.col >= FB_CON_COLS) { fbcon.col = 0; fbcon.row++; }
    } else if (c == '\b') {
        if (fbcon.col > 0) {
            fbcon.col--;
            fb_draw_char(' ', fbcon.col, fbcon.row, FB_COLOR_WHITE, FB_COLOR_BLACK);
        }
    } else {
        fb_draw_char(c, fbcon.col, fbcon.row, FB_COLOR_WHITE, FB_COLOR_BLACK);
        fbcon.col++;
        if (fbcon.col >= FB_CON_COLS) { fbcon.col = 0; fbcon.row++; }
    }
    /* Scroll when we hit the bottom */
    if (fbcon.row >= FB_CON_ROWS) {
        fb_scroll();
        fbcon.row = FB_CON_ROWS - 1;
    }
}

static inline void fbcon_puts(const char *s)
{
    while (*s)
        fbcon_putc(*s++);
}

/* Draw a blinking-style cursor underline at current position. */
static inline void fbcon_draw_cursor(void)
{
    if (!fbcon.initialized) return;
    int x0 = fbcon.col * FB_FONT_W;
    int y0 = fbcon.row * FB_FONT_H + FB_FONT_H - 2;
    fb_rect(x0, y0, FB_FONT_W, 2, FB_COLOR_WHITE);
}

