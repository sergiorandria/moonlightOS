_Static_assert(sizeof(ml_wc_tab) == 256, "wctype table must cover 0x00-0xFF");

static unsigned ml_wc_flags(wint_t c) {
    if (c < 0 || c > 0x10FFFF) return 0;
    if (c < 256) return ml_wc_tab[c];
    /* Unicode White_Space past Latin-1 (explicit list). */
    switch (c) {
    case 0x1680:
    case 0x2000:
    case 0x2001:
    case 0x2002:
    case 0x2003:
    case 0x2004:
    case 0x2005:
    case 0x2006:
    case 0x2007:
    case 0x2008:
    case 0x2009:
    case 0x200A:
    case 0x2028:
    case 0x2029:
    case 0x202F:
    case 0x205F:
    case 0x3000:
        return 0x84; /* space + blank */
    default:
        return 0;
    }
}

int iswalpha(wint_t c) { return (ml_wc_flags(c) & 0x01) != 0; }
int iswdigit(wint_t c) { return (ml_wc_flags(c) & 0x02) != 0; }
int iswalnum(wint_t c) { return (ml_wc_flags(c) & 0x03) != 0; }
int iswspace(wint_t c) { return (ml_wc_flags(c) & 0x04) != 0; }
int iswupper(wint_t c) { return (ml_wc_flags(c) & 0x08) != 0; }
int iswlower(wint_t c) { return (ml_wc_flags(c) & 0x10) != 0; }
int iswxdigit(wint_t c) { return (ml_wc_flags(c) & 0x20) != 0; }
int iswprint(wint_t c) { return (ml_wc_flags(c) & 0x40) != 0; }
int iswblank(wint_t c) { return (ml_wc_flags(c) & 0x80) != 0; }

int iswcntrl(wint_t c) {
    if (c < 0 || c > 0x10FFFF) return 0;
    if (c < 256) return (ml_wc_tab[c] & 0x40) == 0;
    return 0;
}

int iswpunct(wint_t c) {
    unsigned f = ml_wc_flags(c);
    return (f & 0x40) && !(f & 0x03) && !(f & 0x04);
}

int iswgraph(wint_t c) {
    unsigned f = ml_wc_flags(c);
    return (f & 0x40) && !(f & 0x04) && c != ' ';
}

/* Latin-1 case pairs (ASCII handled inline for speed). */
wint_t towlower(wint_t c) {
    if (c >= 'A' && c <= 'Z') return c + 32;
    if (c >= 0xC0 && c <= 0xDE && c != 0xD7) return c + 32;
    return c;
}

wint_t towupper(wint_t c) {
    if (c >= 'a' && c <= 'z') return c - 32;
    if (c >= 0xE0 && c <= 0xFE && c != 0xF7) return c - 32;
    if (c == 0xFF) return 0x178; /* ÿ -> Ÿ (only Latin-1 growth) */
    return c;
}

static const struct {
    const char *name;
    int bit;
} ml_wc_names[] = {
    {"alnum", 0x03}, {"alpha", 0x01}, {"blank", 0x80}, {"cntrl", 0x100},
    {"digit", 0x02}, {"graph", 0x200}, {"lower", 0x10}, {"print", 0x40},
    {"punct", 0x400}, {"space", 0x04}, {"upper", 0x08}, {"xdigit", 0x20},
};

wctype_t wctype(const char *name) {
    size_t i;
    if (!name) return 0;
    for (i = 0; i < sizeof(ml_wc_names) / sizeof(ml_wc_names[0]); i++)
        if (strcmp(name, ml_wc_names[i].name) == 0)
            return ml_wc_names[i].bit;
    return 0;
}

int iswctype(wint_t c, wctype_t d) {
    unsigned f;
    if (d == 0) return 0;
    if (d == 0x100) return iswcntrl(c);
    if (d == 0x200) return iswgraph(c);
    if (d == 0x400) return iswpunct(c);
    f = ml_wc_flags(c);
    if (d == 0x03) return (f & 0x03) != 0;
    return (f & (unsigned)d) != 0;
}

wctrans_t wctrans(const char *name) {
    if (!name) return 0;
    if (strcmp(name, "tolower") == 0) return 1;
    if (strcmp(name, "toupper") == 0) return 2;
    return 0;
}

wint_t towctrans(wint_t c, wctrans_t d) {
    if (d == 1) return towlower(c);
    if (d == 2) return towupper(c);
    return c;
}
