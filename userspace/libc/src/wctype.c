/* libc wctype: ASCII-exact classification + Latin-1 case tables.
 *
 * Bit layout per code point (page tables for 0x00-0xFF):
 *  0x01 alpha  0x02 digit  0x04 space  0x08 upper  0x10 lower
 *  0x20 xdigit 0x40 print  0x80 blank
 * punct = print & ~alnum & ~space; graph = print & ~space;
 * cntrl = ~print (within the 256 range).
 */
#include <wctype.h>
#include <string.h>

