typedef struct {
    int64_t d_tag;
    uint64_t d_val;
} Elf64_Dyn;

#define ELF64_R_SYM(i) ((i) >> 32)
#define ELF64_R_TYPE(i) ((i) & 0xFFFFFFFFu)
#define ELF64_R_INFO(s, t) (((uint64_t)(s) << 32) | (uint64_t)(t))
#define ELF64_ST_BIND(i) ((i) >> 4)
#define ELF64_ST_TYPE(i) ((i) & 0xFu)
#define ELF64_ST_INFO(b, t) (((b) << 4) | ((t) & 0xFu))
